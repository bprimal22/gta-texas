// Regenerates research/whole-campus-92/BLOCKS.md from blocks.json, each <block>/ledger.json and
// status.json (live worker state maintained by the integrator).
//   node tools/blocks/blocks-md.mjs [researchDir]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const ROOT = resolve(import.meta.dirname, '../..');
const dir = resolve(process.argv[2] ?? resolve(ROOT, '../ut/research/whole-campus-92'));
const m = JSON.parse(readFileSync(resolve(dir, 'blocks.json'), 'utf8'));
const status = existsSync(resolve(dir, 'status.json')) ? JSON.parse(readFileSync(resolve(dir, 'status.json'), 'utf8')) : { blocks: {} };
const ledger = id => { const f = resolve(dir, id, 'ledger.json'); return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null; };
const stageCount = (l, k) => l ? l.buildings.filter(b => b.stage?.[k]).length : 0;
let md = `# Whole-campus blocks (whole-campus-92)

Generated by \`local-ut/tools/blocks/blocks-md.mjs\` from \`blocks.json\` (partition: \`local-ut/tools/blocks/partition.mjs\`),
each block's \`<id>/ledger.json\` and \`status.json\`. Do not hand-edit; rerun the generator.

## Why it is organised this way (for a new engineer)

- **One geographic owner per block.** The campus rectangle ${JSON.stringify(m.bounds)} is cut into ${m.blocks.length} blocks along
  measured street centrelines (path medians in \`campus.json\`). The tiling is exact (${m.tiling.samples} grid samples, ${m.tiling.gaps} gaps,
  ${m.tiling.overlaps} overlaps). Every building record and every mapped path has exactly one owning block.
- **Whole-ring rule.** ${m.ringOwnershipRule} ${m.crossBoundaryBuildings.length} footprints cross a zone edge; their owners are listed in \`blocks.json\` → \`crossBoundaryBuildings\`.
- **Shared-edge rule.** ${m.sharedEdges}
- **No shared-file races.** Owners write only \`lib/campus/blocks/<id>/\` (install(), context.json, shots.json), \`scripts/harness/blocks/<id>.ts\`,
  \`public/assets/blocks/<id>/\`, the existing modules listed for their block, and \`research/whole-campus-92/<id>/\`. Root-shared generators
  (${m.rootSharedModules.filter(f => !f.startsWith('public')).join(', ')}) and game/walkway/context/catalog/materials/scans/vegetation/ground are integrator-owned;
  owners request changes in \`lib/campus/blocks/<id>/shared-requests.json\`. One registry (\`lib/campus/blocks/registry.ts\`) connects them.
- **What a block can change.** \`context.json\`: corrected/excluded/added GIS footprints, explicit "replaced by authored geometry", catalogue entry/archetype,
  explicit massing — each with \`evidence {source, basis: measured|official|reference-interpreted|estimate}\`. \`install()\`: authored solids and walkable ground
  whose colliders are built from the same triangles; they join the world/walkway roots, so map travel, scooter ground, the context's coverage raster
  (no duplicate footprint) and tree placement all respect them.
- **Checks.** \`scripts/harness/run-block-checks.mjs\` (generic rules G1–G5 + each block's own check) on the real headless scene; existing route,
  travel, ground, scan and shot-clearance checks keep running. Passing checks prove geometric consistency, **not** real-world resemblance.
- **Ledger stages per record:** inventoried → reference-reviewed → implemented → geometry-verified → visually-reviewed; \`still-inferred\` stays true
  until a source establishes the feature. Visual review is Codex's in-app browser only (currently a pending gate).

## Coverage

- ${m.coverage.buildings} building records (${m.coverage.buildingsAssigned} unique ids; data issues: ${JSON.stringify(m.coverage.dataIssues)}), ${m.coverage.paths} paths, all assigned.
- Exclusions: ${m.coverage.exclusions.length ? JSON.stringify(m.coverage.exclusions) : 'none'}.

## Blocks

| Block | Name | Rectangles [x0,x1,z0,z1] | Units | Records (decisions now) | Paths | Modules | Worker | Reviewed / implemented / geometry-verified |
|---|---|---|---:|---|---:|---:|---|---|
`;
for (const b of m.blocks) {
  const l = ledger(b.id), s = status.blocks[b.id] ?? {};
  const dec = l ? Object.entries(l.summary.decisions).map(([k, v]) => `${k} ${v}`).join(', ') : '';
  md += `| \`${b.id}\` | ${b.name} | ${b.rects.map(r => `[${r.join(',')}]`).join(' ')} | ${b.units.length} | ${b.counts.buildings} (${dec}) | ${b.counts.paths} | ${b.counts.modules} | ${s.worker ?? 'not started'} | ${stageCount(l, 'reference-reviewed')} / ${stageCount(l, 'implemented')} / ${stageCount(l, 'geometry-verified')} |\n`;
}
md += `\n## Focus and live status\n\n`;
for (const b of m.blocks) {
  const s = status.blocks[b.id] ?? {};
  md += `### ${b.id} — ${b.name}\n\n- Focus: ${b.focus}\n- Landmarks: ${b.landmarks.map(l => l.id).join(', ') || 'none'}; existing modules: ${b.modules.length ? b.modules.join(', ') : 'none'}\n- Worker: ${s.worker ?? 'not started'}${s.lane ? ` (lane \`${s.lane}\`)` : ''}\n`;
  if (s.notes?.length) for (const n of s.notes) md += `- ${n}\n`;
  md += `\n`;
}
writeFileSync(resolve(dir, 'BLOCKS.md'), md);
console.log('BLOCKS.md written', md.length, 'chars');
