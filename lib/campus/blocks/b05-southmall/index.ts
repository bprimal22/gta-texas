/** PCL roof outline: context.json footprints[652349] with the north entrance indent closed along the
 * authored north blank wall line (the façade skin stands there to full height), and five small
 * notches/slivers of the City ring (<= 1.5 m wide) dropped. */
export const PCL_ROOF_RING: Point[] = [
  [-123.09, 299.95], [-123.84, 313.3], [-126.24, 345.55], [-142.87, 344.31], [-147.55, 374.94], [-148.82, 390.29],
  [-146.8, 389.49], [-128.21, 411.66], [-103.27, 413.73], [-103.49, 438.95], [-55.1, 397.23],
  [-52.46, 398.62], [-47.52, 338.96], [-85.87, 339.9], [-121.17, 298.87],
];
/** Faces already skinned by pcl-facade.ts (pclFaces endpoints). */
const AUTHORED_FACES: [Point, Point][] = [
  [[-121.17, 298.87], [-85.87, 339.9]], [[-55.1, 397.23], [-103.49, 438.95]],
  [[-47.52, 338.96], [-52.46, 398.62]], [[-85.87, 339.9], [-47.52, 338.96]],
];
/** LiDAR 652349 tier 30.2 m (242 m²), outline squared to its four corners. */
export const PCL_PENTHOUSE: Point[] = [[-91.0, 394.9], [-81.7, 387.7], [-94.5, 372.9], [-102.7, 380.5]];
export const PCL_ROOF_Y = 23.04, PCL_PARAPET_Y = 23.8, PCL_PENTHOUSE_Y = 26.9;
const WALL = 0.35, INSET = 0.3;
/** Deck edge behind an authored face: the skin's recessed bays reach 2.6 m inside (clearance(-2.6, ...)
 * in pcl-facade.ts) and its own roof strip covers that band, so the deck starts 2.9 m in (no collider in the
 * skin's reveals); a collider-free visual strip closes the 0.3 m seam under the strip edge. */
const SKIN_INSET = 2.9;

/** Offset each edge of a positive ring inward by its own distance (line intersection at vertices). */
function insetRing(ring: Point[], dist: (i: number) => number): Point[] {
  const n = ring.length, lines = ring.map((a, i) => {
    const b = ring[(i + 1) % n], dx = b[0] - a[0], dz = b[1] - a[1], l = Math.hypot(dx, dz), nx = dz / l, nz = -dx / l, d = dist(i);
    return { p: [a[0] - nx * d, a[1] - nz * d] as Point, u: [dx / l, dz / l] as Point };
  });
  return ring.map((v, i) => {
    const A = lines[(i + n - 1) % n], B = lines[i], den = A.u[0] * B.u[1] - A.u[1] * B.u[0];
    if (Math.abs(den) < 1e-6) return B.p;
    const t = ((B.p[0] - A.p[0]) * B.u[1] - (B.p[1] - A.p[1]) * B.u[0]) / den;
    return [A.p[0] + A.u[0] * t, A.p[1] + A.u[1] * t] as Point;
  });
}

const segDist = (p: Point, a: Point, b: Point) => {
  const dx = b[0] - a[0], dz = b[1] - a[1], l = dx * dx + dz * dz;
  const t = l ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dz) / l)) : 0;
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dz);
};
const onAuthored = (a: Point, b: Point) => AUTHORED_FACES.some(([p, q]) => segDist(a, p, q) < 0.6 && segDist(b, p, q) < 0.6);
const ccw = (r: Point[]) => (signedArea(r) > 0 ? r.slice() : r.slice().reverse());

class Tris {
  p: number[] = [];
  tri(a: THREE.Vector3, b: THREE.Vector3, c: THREE.Vector3) { this.p.push(a.x, a.y, a.z, b.x, b.y, b.z, c.x, c.y, c.z); }
  /** Quad a-b-c-d; facing = outward normal used to fix the winding. */
  quad(a: THREE.Vector3, b: THREE.Vector3, c: THREE.Vector3, d: THREE.Vector3, facing: THREE.Vector3) {
    const n = new THREE.Vector3().crossVectors(new THREE.Vector3().subVectors(b, a), new THREE.Vector3().subVectors(c, a));
    if (n.dot(facing) < 0) { this.tri(a, c, b); this.tri(a, d, c); } else { this.tri(a, b, c); this.tri(a, c, d); }
  }
  /** Horizontal polygon at y (facing up or down). */
  cap(ring: Point[], y: number, up: boolean) {
    const r = ccw(ring), tris = THREE.ShapeUtils.triangulateShape(r.map(([x, z]) => new THREE.Vector2(x, z)), []);
    for (const [i, j, k] of tris) {
      const a = new THREE.Vector3(r[i][0], y, r[i][1]), b = new THREE.Vector3(r[j][0], y, r[j][1]), c = new THREE.Vector3(r[k][0], y, r[k][1]);
      const n = new THREE.Vector3().crossVectors(new THREE.Vector3().subVectors(b, a), new THREE.Vector3().subVectors(c, a));
      if ((n.y > 0) === up) this.tri(a, b, c); else this.tri(a, c, b);
    }
  }
  /** Vertical prism walls of a positive ring (exterior normal (dz, -dx)) from bottom(x,z) to top. */
  sides(ring: Point[], bottom: (x: number, z: number) => number, top: number, keep: (i: number) => boolean = () => true, sign = 1) {
    for (let i = 0; i < ring.length; i++) {
      if (!keep(i)) continue;
      const a = ring[i], b = ring[(i + 1) % ring.length], dx = b[0] - a[0], dz = b[1] - a[1], l = Math.hypot(dx, dz);
      if (l < 0.05) continue;
      const out = new THREE.Vector3(dz / l, 0, -dx / l).multiplyScalar(sign);
      this.quad(new THREE.Vector3(a[0], bottom(a[0], a[1]), a[1]), new THREE.Vector3(b[0], bottom(b[0], b[1]), b[1]),
        new THREE.Vector3(b[0], top, b[1]), new THREE.Vector3(a[0], top, a[1]), out);
    }
  }
  geometry() {
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(this.p, 3));
    g.computeVertexNormals();
    const uv: number[] = [], pos = g.getAttribute('position'), nor = g.getAttribute('normal');
    for (let i = 0; i < pos.count; i++) { // metre UVs: planar by dominant normal
      const ny = Math.abs(nor.getY(i)), x = pos.getX(i), y = pos.getY(i), z = pos.getZ(i);
      if (ny > 0.7) uv.push(x / 2, z / 2); else uv.push((Math.abs(nor.getX(i)) > Math.abs(nor.getZ(i)) ? z : x) / 2, y / 2);
    }
    g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
    g.computeBoundingBox(); g.computeBoundingSphere();
    return g;
  }
}

function buildPclBody(ctx: BlockInstallContext) {
  const ground = (x: number, z: number) => ctx.groundHeight(x, z) - 0.6;
  const roofRing = ccw(PCL_ROOF_RING);
  const authored = (i: number) => onAuthored(roofRing[i], roofRing[(i + 1) % roofRing.length]);
  const open = (i: number) => !authored(i);
  const deck = insetRing(roofRing, i => (authored(i) ? SKIN_INSET : INSET));
  const wallInner = insetRing(roofRing, () => WALL);
  const t = new Tris(), seam = new Tris();
  // Roof deck (top) and its underside.
  t.cap(deck, PCL_ROOF_Y, true);
  t.cap(deck, PCL_ROOF_Y - 0.3, false);
  // Visual-only seam strip (no collider) between the skin's roof strip (2.6 m) and the deck (2.9 m).
  const seamInner = insetRing(roofRing, i => (authored(i) ? SKIN_INSET : INSET)), seamOuter = insetRing(roofRing, i => (authored(i) ? 2.5 : INSET));
  for (let i = 0; i < roofRing.length; i++) if (authored(i)) { const j = (i + 1) % roofRing.length; seam.cap([seamOuter[i], seamOuter[j], seamInner[j], seamInner[i]], PCL_ROOF_Y - 0.02, true); }
  // Walls on the edges the authored skin does not cover: outer face, inner (roof-side) face, parapet cap.
  t.sides(roofRing, ground, PCL_PARAPET_Y, open, 1);
  t.sides(wallInner, () => PCL_ROOF_Y - 0.3, PCL_PARAPET_Y, open, -1);
  for (let i = 0; i < roofRing.length; i++) {
    if (!open(i)) continue;
    const j = (i + 1) % roofRing.length;
    t.cap([roofRing[i], roofRing[j], wallInner[j], wallInner[i]], PCL_PARAPET_Y, true);
  }
  // Penthouse (LiDAR tier 30.2 m).
  t.sides(ccw(PCL_PENTHOUSE), () => PCL_ROOF_Y - 0.3, PCL_PENTHOUSE_Y);
  t.cap(PCL_PENTHOUSE, PCL_PENTHOUSE_Y, true);
  return { solid: t.geometry(), seam: seam.p.length ? seam.geometry() : null };
}

function findPclMaterial(ctx: BlockInstallContext): THREE.Material | undefined {
  let found: THREE.Material | undefined;
  ctx.authored.surfaces.traverse(o => {
    const m = o as THREE.Mesh;
    if (!found && m.isMesh && m.name === 'PCL authored façade' && !Array.isArray(m.material)) found = m.material;
  });
  return found;
}

const OWN_COLORS: Record<string, number> = { paving: 0xd8cdb8, lawn: 0x6f8f45, stone: 0xd9cfbb, coping: 0xcfc6b6, bronze: 0x4a4436, hedge: 0x3d5a2c };
const BORROW: Record<string, string> = { paving: 'West Mall aggregate paving', lawn: 'Campus terrain lawn', stone: 'West Mall limestone stairs, walls and bed curbs', coping: 'MLK pale stone platform', bronze: 'MLK charcoal weathered bronze' };

export const block: BlockModule = {
  id: 'b05-southmall',
  install(ctx): BlockInstall {
    const began = performance.now();
    const geometries: THREE.BufferGeometry[] = [], ownMaterials: THREE.Material[] = [], colliders: RAPIER.Collider[] = [];
    let kit: B05Kit | undefined, dkit: DobieKit | undefined;
    // b05 geometry (trisGeometry) has no colour attribute: a borrowed material that multiplies by vertex colours
    // (the MLK stone/bronze) would render black. Use an owned clone with vertexColors off; the shared original is
    // untouched, and the clone shares (never disposes) its textures.
    const compat = new Map<THREE.Material, THREE.Material>();
    const compatible = (m: THREE.Material) => {
      if (!m.vertexColors) return m;
      let c = compat.get(m);
      if (!c) { c = m.clone(); c.vertexColors = false; c.name = `${m.name} (b05, no vertex colours)`; compat.set(m, c); ownMaterials.push(c); }
      return c;
    };
    const mat = (k: string) => {
      const b = BORROW[k] ? ctx.material(BORROW[k]) : undefined;
      if (b) return compatible(b);
      const m = new THREE.MeshStandardMaterial({ color: OWN_COLORS[k] ?? 0xcccccc, roughness: k === 'bronze' ? 0.55 : 0.92, metalness: k === 'bronze' ? 0.6 : 0 });
      m.name = `b05 ${k}`; ownMaterials.push(m); return m;
    };
    const tag = (m: THREE.Mesh, name: string) => { m.name = name; m.castShadow = m.receiveShadow = true; m.userData.block = 'b05-southmall'; return m; };
    try {
      // PCL closure (round 1).
      const { solid: geometry, seam } = buildPclBody(ctx);
      geometries.push(geometry); if (seam) geometries.push(seam);
      const pcl0 = findPclMaterial(ctx), pclMat = pcl0 ? compatible(pcl0) : mat('stone');
      const pcl = tag(new THREE.Mesh(geometry, pclMat), 'b05 PCL roof deck, penthouse and closing walls');
      const detail: THREE.Object3D[] = [];
      if (seam) detail.push(tag(new THREE.Mesh(seam, pclMat), 'b05 PCL roof seam strip (visual)'));
      colliders.push(trimeshCollider(ctx.physics, Array.from(geometry.getAttribute('position').array as Float32Array)));
      // South Mall south of z 170 + Littlefield Fountain (round 2).
      const sm = buildSouthMall(ctx);
      const walkable: THREE.Object3D[] = [], solids: THREE.Object3D[] = [pcl];
      const names: Record<string, string> = { paving: 'b05 South Mall walks, terrace and fountain plaza', lawn: 'b05 South Mall lawn', stone: 'b05 Littlefield Fountain stone', coping: 'b05 Littlefield Fountain granite coping', bronze: 'b05 Littlefield Fountain bronze group', hedge: 'b05 Littlefield Fountain hedges' };
      let walkTris = 0, solidTris = 0;
      const walkPos: number[] = [];
      for (const [k, t] of sm.walkable) { if (!t.count) continue; const geo = trisGeometry(t); geometries.push(geo); walkable.push(tag(new THREE.Mesh(geo, mat(k)), k === 'stone' ? 'b05 South Mall terrace stairs' : names[k])); for (const v of t.p) walkPos.push(v); walkTris += t.count; }
      if (walkPos.length) colliders.push(trimeshCollider(ctx.physics, walkPos));
      const solidPos: number[] = [];
      for (const [k, t] of sm.solid) { if (!t.count) continue; const geo = trisGeometry(t); geometries.push(geo); solids.push(tag(new THREE.Mesh(geo, mat(k)), names[k])); for (const v of t.p) solidPos.push(v); solidTris += t.count; }
      if (solidPos.length) colliders.push(trimeshCollider(ctx.physics, solidPos));
      const waterMat = new THREE.MeshStandardMaterial({ color: 0x5b93a3, roughness: 0.12, metalness: 0.15 }); waterMat.name = 'b05 Littlefield Fountain water'; ownMaterials.push(waterMat);
      const wgeo = trisGeometry(sm.water); geometries.push(wgeo);
      const water = new THREE.Mesh(wgeo, waterMat); water.name = 'b05 Littlefield Fountain water (visual)'; water.receiveShadow = true; water.userData.block = 'b05-southmall'; detail.push(water);
      // D08/D09/D10 authored architecture (round 4): private PBR kit, one collider per building group.
      kit = new B05Kit(ctx.renderer);
      const hrc = buildHrc(ctx), six = buildSixPack(ctx), att = buildAtt(ctx), bma = buildHall(ctx, BMA_SPEC), bms = buildHall(ctx, BMS_SPEC), petals = buildPetals(ctx);
      const districtStats: Record<string, unknown> = {};
      for (const [part, built, localContext, record] of [
        ['D08 HRC', hrc, false, HRC_KEY], ['D08 Batts-Mezes-Benedict', six, true, '714471:1095'], ['D09 ATT', att, true, '505680:201'],
        ['D10 BMA', bma, false, BMA_SPEC.key], ['D10 BMS', bms, false, BMS_SPEC.key], ['D10 Blanton petals', petals, true, undefined],
      ] as const) {
        const b = built.group.build(kit, ctx.physics, { localContext, record });
        geometries.push(...b.geometries); if (b.collider) colliders.push(b.collider);
        solids.push(...b.solids); detail.push(...b.detail);
        districtStats[part] = { ...built.stats, solidTriangles: b.solidTris, trimTriangles: b.detailTris, colliderTriangles: b.colliderTris, meshes: b.solids.length + b.detail.length };
      }
      // D10 Blanton plaza paving (round 5): walkable ground draped on the terrain, render = collider triangles.
      const plaza = buildPlazaPaving(ctx, kit);
      geometries.push(plaza.geometry); colliders.push(plaza.collider); walkable.push(plaza.mesh);
      // D08 Dobie Twenty21 (round 6): replaces the generated tiers with an authored body on the same measured rings and
      // heights (d21.ts); Dobie-private materials, one collider from exactly its solid triangles.
      dkit = new DobieKit(ctx.renderer);
      const d21 = buildDobie(ctx, kit, dkit, ctx.physics);
      geometries.push(...d21.geometries); colliders.push(d21.collider); solids.push(...d21.solids); detail.push(...d21.detail);
      districtStats['D08 D21'] = d21.stats;
      const replaced = [HRC_KEY, BMA_SPEC.key, BMS_SPEC.key, D21_KEY];
      return {
        solids, walkable, detail, colliders, replaced,
        stats: { triangles: geometries.reduce((s, g) => s + g.getAttribute('position').count / 3, 0), walkableTriangles: walkTris, solidTriangles: solidTris,
          meshes: solids.length + walkable.length + detail.length, colliders: colliders.length, ownMaterials: ownMaterials.length,
          pcl: { roofY: PCL_ROOF_Y, penthouseY: PCL_PENTHOUSE_Y }, southMall: sm.stats, districts: districtStats, sixPackDormers: six.dormers, sixPackPieces: six.pieces,
          plaza: plaza.stats, pbr: kit.stats(), dobie: dkit.stats(), installMs: +(performance.now() - began).toFixed(1) },
        dispose() {
          for (const c of colliders) if (ctx.physics.getCollider(c.handle)) ctx.physics.removeCollider(c, false);
          for (const g of geometries) g.dispose(); for (const m of ownMaterials) m.dispose(); kit?.dispose(); dkit?.dispose();
        },
      };
    } catch (e) {
      for (const c of colliders) if (ctx.physics.getCollider(c.handle)) ctx.physics.removeCollider(c, false);
      for (const g of geometries) g.dispose(); for (const m of ownMaterials) m.dispose(); kit?.dispose(); dkit?.dispose();
      throw e;
    }
  },
};
