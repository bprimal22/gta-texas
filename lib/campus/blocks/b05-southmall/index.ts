// install() closes the Perry-Castañeda Library body. The authored PCL package (pcl-facade.ts) was
// written as a skin over a streamed source roof that the offline build no longer has: it renders
// only the four east faces, so from above and from the west/south the library was an open shell
// (top-down rays inside it hit the terrain). This adds, from the same triangles for render and
// collision:
//  - the roof deck at campus Y 23.04 over the PCL part of City ring 652349 (LiDAR tier 26.2 m above
//    groundY -3.3 = Y 22.9; 23.04 meets the authored roof strip in pcl-facade.ts),
//  - plain concrete walls on every PCL edge the authored skin does not cover (light court, the
//    official PCL/UTC edge, the west wing and the south notches), ground to the 23.8 m parapet line,
//  - the measured 30.2 m roof tier (242 m², campus Y 26.9) as a penthouse box.
// UTC, the west part of the same City record, is regenerated by the context (context.json add -501).
